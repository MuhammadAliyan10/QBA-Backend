# DAG COMPILER
# =============================================================================

def compile_recipe_from_microplan(plan: MicroPlan, context: str) -> Recipe:
    nodes = []
    edges = []

    # 1. Generate System Boilerplate natively in Python
    recipe_id = f"rec_{uuid.uuid4().hex[:8]}"
    name = "Auto-generated"
    if "objective" in context.lower():
        # Quick extract for naming
        name = f"Auto-generated: {context[:40]}"

    metadata = RecipeMetadata(
        id=recipe_id,
        name=name,
        created_at=datetime.now(timezone.utc)
    )

    # 2. Translate Intents to Nodes and Link Edges deterministically
    previous_node_id = None
    entry_point = None

    for idx, intent in enumerate(plan.subtasks):
        node_id = f"node_{idx}"
        if idx == 0:
            entry_point = node_id

        # Map basic types to ActionType enum
        action_map = {
            "NAVIGATE": ActionType.NAVIGATE,
            "CLICK": ActionType.CLICK,
            "DOUBLECLICK": ActionType.CLICK,
            "TYPE": ActionType.TYPE,
            "PRESS_ENTER": ActionType.TYPE,
            "EXTRACT": ActionType.EXTRACT,
            "EXTRACT_TABLE": ActionType.EXTRACT_TABLE,
            "WAIT": ActionType.WAIT,
            "WAIT_HIDDEN": ActionType.WAIT_HIDDEN,
            "SCREENSHOT": ActionType.SCREENSHOT,
            "SCROLL": ActionType.SCROLL,
            "HOVER": ActionType.HOVER,
            "SELECT": ActionType.SELECT,
            "CHECK": ActionType.CHECK,
        }

        mapped_type = action_map.get(intent.action.upper(), ActionType.CLICK)

        # Combine Semantic Anchors into a single dense string for the transformer
        # This solves the "Semantic Surface Area" problem
        semantic_target = ", ".join(intent.semantic_anchors) if intent.semantic_anchors else "Element"

        # Build your heavy Node structure here using Python, not AI
        action = Action(
            seq=1,
            type=mapped_type,
            intent=semantic_target,
            value=intent.value,
        )

        node = Node(
            id=node_id,
            name=intent.action,
            type=NodeType.ACTION,
            execution=ExecutionConfig(timeout_ms=30000),
            actions=[action]
        )
        nodes.append(node)

        if previous_node_id:
            edges.append(Edge(source=previous_node_id, target=node_id))
        previous_node_id = node_id

    # 3. Define standard exit points
    # Fallback if no nodes
    if not previous_node_id:
        previous_node_id = "node_end"
        entry_point = previous_node_id

    exit_points = ExitPoints(
        success=previous_node_id, # Last node is success
        failure="global_error_handler",
        timeout="global_timeout_handler"
    )

    return Recipe(
        metadata=metadata,
        nodes=nodes,
        edges=edges,
        entry_point=entry_point or "node_end",
        exit_points=exit_points
    )

