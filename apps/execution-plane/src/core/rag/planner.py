class ActionIntent(BaseModel):
    """
    Minimal representation of a browser action for token efficiency.
    """
    action: str  # CLICK, TYPE, EXTRACT, etc.
    semantic_anchors: list[str] = Field(default_factory=list)  # 4-6 synonyms/contextual clues for vector search
    value: Optional[str] = None  # Text to type or value to select
    timeout: Optional[int] = None

class MicroPlan(BaseModel):
    """
    The 'Soft Recipe' generated by the LLM.
    Focuses only on strategic subtasks.
    """
    subtasks: list[ActionIntent]

# =============================================================================
# RESULT TYPE (Legacy support)
# =============================================================================

from dataclasses import dataclass

@dataclass
class PlannerResult:
    """Result of recipe generation (Legacy support for RAG orchestrator)."""
    success: bool
    recipe: Optional[Dict] = None
    error: Optional[str] = None
    generation_ms: int = 0
    model_used: str = "meta/llama-3.1-8b-instruct"
    tokens_used: int = 0

