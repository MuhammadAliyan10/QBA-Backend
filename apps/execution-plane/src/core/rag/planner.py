class RecipePlanner:
    """
    LLM-Powered Recipe Generator using NVIDIA NIM REST API.
    Enforces strict structured outputs via Pydantic model_json_schema.
    """

    def __init__(self):
        self.api_key = os.getenv("NVIDIA_API_KEY")
        if not self.api_key:
            logger.warning("[Planner] NVIDIA_API_KEY is missing. Requests will fail.")

    async def generate_with_retry(
        self,
        prompt: str,
        url: str,
        classification: Optional[Dict] = None,
        job_id: Optional[str] = None
    ) -> Recipe:
        """
        Main entry point with autonomous retry loop and self-correction.
        """
        messages = [
            {"role": "system", "content": PLANNER_SYSTEM_PROMPT},
            {"role": "user", "content": self._build_user_message(prompt, url, classification)}
        ]

        # Generate JSON Schema from Pydantic Model
        microplan_schema = MicroPlan.model_json_schema()

        response_format = {
            "type": "json_schema",
            "json_schema": {
                "name": "microplan",
                "schema": microplan_schema,
                "strict": True
            }
        }

        attempts = 0
        while attempts < MAX_RETRIES:
            attempts += 1
            logger.info(f"[Planner] Generation attempt {attempts}/{MAX_RETRIES}")

            try:
                # 1. Raw HTTP Request via Global Singleton Client
                response_content = await self._call_nim(messages, response_format)

                # 2. Local Pydantic Gatekeeping (Validation)
                try:
                    logger.info(f"[Planner] LLM output received: len={len(response_content)}")

                    # BEST POSSIBLE FIX: Markdown/Conversational Stripper
                    # Extracts the raw JSON object directly from the LLM output buffer
                    clean_content = response_content
                    start_idx = clean_content.find('{')
                    end_idx = clean_content.rfind('}')
                    if start_idx != -1 and end_idx != -1 and end_idx >= start_idx:
                        clean_content = clean_content[start_idx:end_idx+1]
                    else:
                        clean_content = clean_content.strip()

                    micro_plan = MicroPlan.model_validate_json(clean_content)

                    # 3. Python builds the massive DAG
                    recipe = compile_recipe_from_microplan(micro_plan, prompt)

                    logger.info(f"✅ [Planner] Successfully compiled recipe: {recipe.metadata.name}")

                    # TELEMETRY INJECTION
                    if job_id:
                        from core.NervousSystem import NervousSystem
                        telemetry_payload = json.dumps({
                            "type": "log",
                            "message": f"[Planner] Compiled DAG: {recipe.model_dump_json()}"
                        })
                        await NervousSystem.publish(f"quanta.telemetry.{job_id}", telemetry_payload)

                    return recipe

                except ValidationError as ve:
                    error_details = ve.json(indent=2)
                    logger.warning(f"❌ [Planner] Pydantic Validation Failed (Attempt {attempts})")
                    logger.error(f"[Planner] Validation Errors: {error_details}")
                    logger.error(f"[Planner] LLM Output: {response_content}")

                    # 4. Feed Error Back to LLM for Self-Correction
                    messages.append({"role": "assistant", "content": response_content})
                    messages.append({
                        "role": "user",
                        "content": f"JSON validation failed. Fix these exact schema errors:\n{error_details}"
                    })
                    continue

            except Exception as e:
                logger.error(f"[Planner] API or Network Error: {e}")
                if attempts >= MAX_RETRIES:
                    raise CompilationFailedError(f"HTTP/API failure after {MAX_RETRIES} attempts: {e}")
                await asyncio.sleep(1) # Tiny backoff

        raise CompilationFailedError(f"Exhausted {MAX_RETRIES} attempts. LLM failed to produce a valid schema.")

    async def generate(
        self,
        prompt: str,
        url: str,
        classification: Optional[Dict] = None,
        similar_template: Optional[Dict] = None,
        job_id: Optional[str] = None
    ) -> PlannerResult:
        """
        Orchestration wrapper for Preflight pipeline.
        """
        start_time = time.time()
        try:
            recipe = await self.generate_with_retry(prompt, url, classification, job_id=job_id)
            duration = int((time.time() - start_time) * 1000)
            return PlannerResult(
                success=True,
                recipe=recipe.model_dump(),
                generation_ms=duration
            )
        except Exception as e:
            logger.error(f"[Planner] Generation failed: {e}")
            return PlannerResult(
                success=False,
                error=str(e),
                generation_ms=int((time.time() - start_time) * 1000)
            )

    async def _call_nim(self, messages: list[dict[str, str]], response_format: Dict) -> str:
        """Execute raw HTTP request to NVIDIA NIM API."""
        client = GetClient()

        payload = {
            "model": NIM_MODEL,
            "messages": messages,
            "temperature": 0.1,
            "response_format": response_format
        }

        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {self.api_key}"
        }

        response = await client.post(NIM_API_URL, json=payload, headers=headers)

        if response.status_code != 200:
            logger.error(f"[Planner] NIM API Error: {response.text}")
            response.raise_for_status()

        data = response.json()
        return data["choices"][0]["message"]["content"]

    def _build_user_message(self, prompt: str, url: str, classification: Optional[Dict]) -> str:
        """Formats the user context for the LLM."""
        context = f"## TARGET URL\n{url}\n\n## USER REQUEST\n{prompt}\n"
        if classification:
            context += f"\n## PAGE CONTEXT\n{json.dumps(classification, indent=2)}"

        context += "\n\nGenerate the Recipe DAG JSON now."
        return context

